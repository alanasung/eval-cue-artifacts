class TestErrorPaths:
    def test_a_single_component_is_refused(self, planted):
        with pytest.raises(ValueError, match="need at least 2 components"):
            analyze_component_failure(
                ["only"],
                planted.target,
                planted.gate_true,
                planted.predict_fn,
                threshold=0.5,
                tolerance=0.1,
                confidence_margin=0.2,
            )

    def test_the_single_component_message_explains_why(self, planted):
        with pytest.raises(ValueError, match="leave-one-out attribution"):
            analyze_component_failure(
                ["only"],
                planted.target,
                planted.gate_true,
                planted.predict_fn,
                threshold=0.5,
                tolerance=0.1,
                confidence_margin=0.2,
            )

    def test_duplicate_component_names_are_refused(self, planted):
        with pytest.raises(ValueError, match="component names must be unique"):
            analyze_component_failure(
                ["a", "a", "b"],
                planted.target,
                planted.gate_true,
                planted.predict_fn,
                threshold=0.5,
                tolerance=0.1,
                confidence_margin=0.2,
            )

    @pytest.mark.parametrize("margin", [-0.1, -1.0])
    def test_negative_confidence_margin_is_refused(self, planted, margin):
        with pytest.raises(ValueError, match="confidence_margin must be non-negative"):
            analyze_component_failure(
                planted.components,
                planted.target,
                planted.gate_true,
                planted.predict_fn,
                threshold=0.5,
                tolerance=0.1,
                confidence_margin=margin,
            )

    def test_target_and_gate_shape_disagreement_is_refused(self, planted):
        with pytest.raises(ValueError, match="target and gate_true disagree"):
            analyze_component_failure(
                planted.components,
                planted.target,
                planted.gate_true[:5],
                planted.predict_fn,
                threshold=0.5,
                tolerance=0.1,
                confidence_margin=0.2,
            )

    def test_a_predict_fn_returning_the_wrong_length_is_refused(self, planted):
        def truncating(present):
            return planted.predict_fn(present)[:5]

        with pytest.raises(ValueError, match="expected \\(12,\\) \\(one prediction per example\\)"):
            analyze_component_failure(
                planted.components,
                planted.target,
                planted.gate_true,
                truncating,
                threshold=0.5,
                tolerance=0.1,
                confidence_margin=0.2,
            )

    def test_the_shape_error_names_the_subset(self, planted):
        def truncating(present):
            return planted.predict_fn(present)[:5]

        with pytest.raises(ValueError, match=r"predict_fn\(\[.*\]\) returned shape"):
            analyze_component_failure(
                planted.components,
                planted.target,
                planted.gate_true,
                truncating,
                threshold=0.5,
                tolerance=0.1,
                confidence_margin=0.2,
            )
