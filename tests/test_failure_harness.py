class TestComplementarityMatrix:
    def test_matrix_lists_its_components(self, report, planted):
        assert report.complementarity["matrix"]["components"] == planted.components

    def test_matrix_is_square(self, report):
        values = report.complementarity["matrix"]["values"]
        assert len(values) == 3
        assert all(len(row) == 3 for row in values)

    def test_diagonal_is_the_solo_mae(self, report):
        values = report.complementarity["matrix"]["values"]
        solo = report.complementarity["solo_mae"]
        for i, name in enumerate(report.components):
            assert values[i][i] == pytest.approx(solo[name], abs=1e-6)

    def test_matrix_is_symmetric(self, report):
        values = np.array(report.complementarity["matrix"]["values"])
        assert np.allclose(values, values.T)

    @pytest.mark.parametrize(
        ("i", "j", "expected"),
        [(0, 1, 0.57 / 12), (0, 2, 1.57 / 12), (1, 2, 0.01)],
    )
    def test_off_diagonal_pairs_are_hand_computed(self, report, i, j, expected):
        values = report.complementarity["matrix"]["values"]
        assert values[i][j] == pytest.approx(expected, abs=1e-6)


class TestStratifiedAttribution:
    @pytest.fixture
    def grouped_report(self, planted):
        return analyze_component_failure(
            planted.components,
            planted.target,
            planted.gate_true,
            planted.predict_fn,
            threshold=planted.threshold,
            tolerance=planted.tolerance,
            confidence_margin=planted.confidence_margin,
            groups=planted.groups(),
        )

    def test_groups_are_optional(self, report):
        assert "winners_by_group" not in report.complementarity

    def test_supplying_groups_adds_the_block(self, grouped_report):
        assert "winners_by_group" in grouped_report.complementarity

    def test_the_attribute_name_is_preserved(self, grouped_report):
        assert set(grouped_report.complementarity["winners_by_group"]) == {"half"}

    def test_every_level_appears(self, grouped_report):
        levels = grouped_report.complementarity["winners_by_group"]["half"]
        assert set(levels) == {"lo", "hi"}

    @pytest.mark.parametrize("level", ["lo", "hi"])
    def test_per_level_counts_are_hand_computed(self, grouped_report, level):
        counts = grouped_report.complementarity["winners_by_group"]["half"][level]
        assert counts == {"a": 3, "b": 2, "c": 1}

    def test_level_counts_sum_to_the_overall_counts(self, grouped_report, planted):
        levels = grouped_report.complementarity["winners_by_group"]["half"]
        total = {name: 0 for name in planted.components}
        for counts in levels.values():
            for name, value in counts.items():
                total[name] += value
        assert total == planted.expected_winners


class TestRecoveryAcrossSeeds:
    """The instrument must recover planted structure, not just one lucky draw."""

    @pytest.mark.parametrize("seed", list(range(12)))
    def test_marginal_value_recovers_the_planted_ordering(self, linear_planted_factory, seed):
        case = linear_planted_factory(seed)
        result = analyze_component_failure(
            case["components"],
            case["target"],
            case["gate_true"],
            case["predict_fn"],
            threshold=0.0,
            tolerance=0.1,
            confidence_margin=0.2,
        )
        marginal = result.complementarity["marginal_value"]
        assert marginal["strong"] > marginal["weak"]

    def test_recovery_rate_is_total_over_twelve_seeds(self, linear_planted_factory):
        recovered = 0
        for seed in range(12):
            case = linear_planted_factory(seed)
            result = analyze_component_failure(
                case["components"],
                case["target"],
                case["gate_true"],
                case["predict_fn"],
                threshold=0.0,
                tolerance=0.1,
                confidence_margin=0.2,
            )
            marginal = result.complementarity["marginal_value"]
            recovered += marginal["strong"] > marginal["weak"]
        assert recovered == 12

    def test_generalizes_beyond_two_components(self, planted):
        """Three components exercise the pair matrix, which two never do."""
        result = analyze_component_failure(
            planted.components,
            planted.target,
            planted.gate_true,
            planted.predict_fn,
            threshold=planted.threshold,
            tolerance=planted.tolerance,
            confidence_margin=planted.confidence_margin,
        )
        assert len(result.complementarity["matrix"]["values"]) == 3


