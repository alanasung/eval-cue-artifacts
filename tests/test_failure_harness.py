"""The model-agnostic failure harness, run against a planted answer.

This is a test of the measurement instrument. The synthetic case in
``conftest.PlantedCase`` is built so that every number the harness reports can
be recomputed by hand from twelve targets and four small prediction vectors, so
these assertions compare against arithmetic a reader can check rather than
against a golden file that could have been generated by the bug.

The planted structure deliberately dissociates the two axes the harness
measures: ``b`` is the most valuable component but fails loudly, while ``c`` is
less valuable and fails silently. A harness that collapsed value and silence
into one number would name the same component for both.
"""

import numpy as np
import pytest

from evalaware.evaluation.failure import FailureReport, analyze_component_failure


@pytest.fixture
def report(planted):
    return analyze_component_failure(
        planted.components,
        planted.target,
        planted.gate_true,
        planted.predict_fn,
        threshold=planted.threshold,
        tolerance=planted.tolerance,
        confidence_margin=planted.confidence_margin,
    )


class TestSubsetEnumeration:
    def test_the_harness_asks_only_for_subsets_it_needs(self, report):
        """PlantedCase.predict_fn raises on any unplanned subset."""
        assert report is not None

    def test_every_planned_subset_was_requested(self, planted, report):
        keys = set(report.predictions) - {"__target__", "__gate__"}
        expected = {",".join(sorted(subset)) for subset in planted.table}
        assert keys == expected

    def test_seven_subsets_for_three_components(self, report):
        assert len(set(report.predictions) - {"__target__", "__gate__"}) == 7

    def test_the_full_set_is_included(self, report):
        assert "a,b,c" in report.predictions

    @pytest.mark.parametrize("name", ["a", "b", "c"])
    def test_every_singleton_is_included(self, report, name):
        assert name in report.predictions

    @pytest.mark.parametrize("pair", ["a,b", "a,c", "b,c"])
    def test_every_pair_is_included(self, report, pair):
        assert pair in report.predictions


